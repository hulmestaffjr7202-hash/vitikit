/* ============================================================
   VitiKit Pro — Spray Record PDF Generator
   纯前端 PDF 生成（window.print 方案，零依赖零成本）
   免费版：完整功能试用 3 次记录（localStorage 计数）
   Pro 版：无限记录 + 自定义农场 Logo
   ============================================================ */

const SprayLog = (() => {
  const LS_KEY = 'vitikit_spraylog_count';
  const LS_PRO = 'vitikit_pro_license';

  function getCount() { return +(localStorage.getItem(LS_KEY) || 0); }
  function isPro() { return !!localStorage.getItem(LS_PRO); }
  function useOne() { localStorage.setItem(LS_KEY, getCount() + 1); }
  function remaining() { return isPro() ? Infinity : Math.max(0, 3 - getCount()); }
  function activatePro(key) {
    // 简单离线校验：VK-开头 + 12位大写字母数字
    if (/^VK-[A-Z0-9]{12}$/.test((key || '').trim().toUpperCase())) {
      localStorage.setItem(LS_PRO, key.trim().toUpperCase());
      return true;
    }
    return false;
  }

  // ---------- 表单数据结构 ----------
  // record: { farm, block, date, product, epaNo, rate, rateUnit, waterL, areaHa,
  //           rei, phi, target, applicator, equipment, wind, temp, notes }

  function validateRecord(r) {
    const missing = [];
    if (!r.farm) missing.push('Farm name');
    if (!r.block) missing.push('Block');
    if (!r.date) missing.push('Date');
    if (!r.product) missing.push('Product');
    if (!r.rate) missing.push('Rate');
    if (!r.waterL) missing.push('Water volume');
    if (!r.areaHa) missing.push('Area treated');
    return missing;
  }

  // ---------- 生成打印视图 ----------
  function buildPrintDocument(r) {
    const esc = s => String(s || '—').replace(/&/g,'&amp;').replace(/</g,'&lt;');
    const rows = [
      ['Date of application', r.date],
      ['Farm / Vineyard', r.farm],
      ['Block', r.block],
      ['Area treated (ha)', r.areaHa],
      ['Target pest / disease', r.target],
      ['Product name', r.product],
      ['EPA / Registration No.', r.epaNo],
      ['Label rate', r.rate ? `${r.rate} ${r.rateUnit || ''}` : ''],
      ['Water volume (L/ha)', r.waterL],
      ['Total product used', r.rate && r.areaHa ? `${(parseFloat(r.rate)*10*parseFloat(r.areaHa)/1000).toFixed(2)} L (est.)` : ''],
      ['Re-entry interval (REI)', r.rei ? `${r.rei} h` : ''],
      ['Pre-harvest interval (PHI)', r.phi ? `${r.phi} days` : ''],
      ['Applicator', r.applicator],
      ['Equipment', r.equipment],
      ['Wind / Temp at application', [r.wind ? `${r.wind} km/h` : '', r.temp ? `${r.temp} °C` : ''].filter(Boolean).join(' / ') || ''],
      ['Notes', r.notes]
    ];
    const tableRows = rows.map(([k, v]) =>
      `<tr><td class="lbl">${esc(k)}</td><td class="val">${esc(v)}</td></tr>`).join('');
    return `<!DOCTYPE html><html><head><meta charset="utf-8">
      <title>Spray Record — ${esc(r.farm)} ${esc(r.block)} ${esc(r.date)}</title>
      <style>
        *{margin:0;padding:0;box-sizing:border-box}
        body{font-family:-apple-system,'Segoe UI',Roboto,sans-serif;color:#1d1d1f;padding:48px;max-width:800px;margin:0 auto}
        .head{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:2px solid #1d1d1f;padding-bottom:16px;margin-bottom:8px}
        h1{font-size:22px;letter-spacing:-.02em}
        .brand{font-size:11px;color:#86868b;margin-top:4px}
        .badge{background:#1d1d1f;color:#fff;font-size:10px;padding:4px 12px;border-radius:99px}
        .badge.free{background:#86868b}
        table{width:100%;border-collapse:collapse;margin-top:20px}
        td{padding:9px 12px;border-bottom:1px solid rgba(0,0,0,.08);font-size:13px;vertical-align:top}
        td.lbl{width:38%;color:#86868b;font-weight:600}
        td.val{font-weight:500}
        .legal{margin-top:28px;font-size:10px;color:#86868b;line-height:1.5;border-top:1px solid rgba(0,0,0,.08);padding-top:12px}
        .sign{display:flex;gap:40px;margin-top:36px}
        .sign div{flex:1;border-top:1px solid #1d1d1f;padding-top:6px;font-size:11px;color:#86868b}
        @media print{ body{padding:24px} .noprint{display:none} }
      </style></head><body>
      <div class="head">
        <div><h1>Vineyard Spray Application Record</h1>
        <div class="brand">Generated by VitiKit · vitikit.app</div></div>
        <div class="badge ${isPro() ? '' : 'free'}">${isPro() ? 'PRO' : 'FREE TRIAL'}</div>
      </div>
      <table>${tableRows}</table>
      <div class="sign"><div>Applicator signature</div><div>Supervisor signature</div></div>
      <div class="legal">This record documents a pesticide application as required by local regulations.
      The label is legally authoritative. Retain with farm records. VitiKit provides record-keeping tools,
      not agronomic advice.</div>
      </body></html>`;
  }

  function exportPDF(record) {
    const missing = validateRecord(record);
    if (missing.length) return { ok: false, missing };
    if (!isPro() && remaining() <= 0) return { ok: false, paywall: true };

    const w = window.open('', '_blank');
    if (!w) return { ok: false, error: 'Popup blocked — allow popups for this site' };
    w.document.write(buildPrintDocument(record));
    w.document.close();
    w.focus();
    setTimeout(() => { try { w.print(); } catch(e){} }, 350);
    useOne();
    return { ok: true, remaining: remaining() };
  }

  return { getCount, isPro, remaining, activatePro, exportPDF, validateRecord };
})();

if (typeof module !== 'undefined') module.exports = SprayLog;
